"use client";

import { useEffect } from "react";
import { usePathname, useRouter } from "@/i18n/navigation";
import { detectApp } from "@/lib/platform";

/**
 * **أوّل ما يُفتح التطبيق: الرئيسية** — قرار صاحبة المتجر (٠٣-٠٨).
 *
 * التطبيق المثبَّت لا يبدأ من الصفر كالموقع: نظامُ الجهاز يحفظ آخر صفحةٍ
 * كان الزبون فيها ويعيده إليها بعد أيام — فيفتح المتجر فيجد نفسه في
 * «سياسة الخصوصية» أو في نصف طلبٍ قديم، لا في واجهة متجره.
 *
 * وهذه تُعيده إلى الرئيسية **عند الفتح وحده**:
 *
 * | | |
 * |---|---|
 * | فتحةٌ جديدة | لا ختم في `sessionStorage` ⇒ يُعاد إلى الرئيسية |
 * | تنقّلٌ داخل الجلسة | الختم موجود ⇒ لا يُمسّ شيء |
 * | العودة من تطبيقٍ آخر | الجلسة حيّة ⇒ يبقى مكانه، فلا تضيع خطوةٌ نصف مكتوبة |
 *
 * ⚠️ **وفي التطبيق وحده لا في الموقع**: روابط المتجر تُرسَل في واتساب
 *    وانستغرام ويفهرسها جوجل — ومن فتح رابط حسابٍ بعينه فوجد نفسه في
 *    الرئيسية ظنّ الرابط مكسوراً وخرج. فالموقع يفتح حيث أشار الرابط،
 *    وعنوانُ المتجر المجرّد رئيسيّةٌ أصلاً.
 *
 * ⚠️ **والختم يُوضع قبل أي فحص**: لو وُضع بعد شرط «نحن في الرئيسية
 *    أصلاً» لبقيت الجلسة بلا ختم، فيُحسب أوّلُ انتقالٍ إلى الألعاب
 *    فتحةً جديدة ويُقذف الزبون إلى الرئيسية وهو يتصفّح.
 */
export default function StartAtHome() {
  const router = useRouter();
  const path = usePathname();

  useEffect(() => {
    let fresh = false;
    try {
      fresh = sessionStorage.getItem("ramaan.launched") === null;
      sessionStorage.setItem("ramaan.launched", "1");
    } catch {
      return; // متصفّحٌ يمنع التخزين — لا نخمّن فنقذف زبوناً بلا سبب
    }

    if (!fresh || path === "/") return;
    if (!detectApp()) return;

    router.replace("/");
    // مرّةً واحدة عند الفتح — و`path` وقتَها هو الصفحة التي فُتح عليها
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  return null;
}
