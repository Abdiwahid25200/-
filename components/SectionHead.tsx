/**
 * ترويسة قسم — كما في النموذج: وسمٌ صغير بخطّ الأرقام، ثم العنوان.
 *
 * ⚠️ **الوسم لاتينيّ في اللغات الثلاث** (`SECTIONS` · `PUBG MOBILE`):
 *    علامةُ مكانٍ لا جملةٌ تُقرأ، فتبقى واحدةً مهما تبدّلت اللغة —
 *    كما في النموذج الذي اعتمدته صاحبة المتجر.
 *
 * ⚠️ **ولا عمود أخضر بجانب العنوان ولا وصفٌ في طرف السطر**: الوصف كان
 *    يطير إلى الطرف المقابل فيُقرأ عنواناً ثانياً. صار سطراً تحته.
 *
 * 🔎 **والعنوان `h1` لا `h2`** — أُصلح في فحص ٠٤-٠٨: لم يكن في الموقع
 *    كلّه عنوانٌ رئيسيّ واحد، وكل صفحةٍ تبدأ بـ`h2`. وجوجل يقرأ `h1`
 *    ليعرف موضوع الصفحة، والموقع سُجّل عنده قبل يومين — فكان الترتيب
 *    يُخصم بلا مقابل. والشكل لم يتغيّر: `.h2S` هي هي، والوسم وحده تبدّل.
 */
export default function SectionHead({
  title,
  note,
  eyebrow,
}: {
  title: string;
  note?: string;
  /** وسم صغير فوق العنوان يميّز هذه الصفحة عن غيرها */
  eyebrow?: string;
}) {
  return (
    /* أصناف النموذج: `.eyeS` وسماً بخطّ الأرقام و`.h2S` عنواناً ٢١px.
       ⚠️ **بلا `mb`**: الحاوية `.scr-body` تفصل الكتل بـ٢٢px، وهامشٌ
          هنا فوقها يجعل فاصل الترويسة أوسع من كل فاصلٍ في الصفحة. */
    <header className="flex flex-col gap-1">
      {eyebrow && <p className="eyeS">{eyebrow}</p>}
      <h1 className="h2S">{title}</h1>
      {note && <p className="f13 mu mt-0.5">{note}</p>}
    </header>
  );
}
