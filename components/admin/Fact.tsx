/**
 * سطرُ بيان — **يختفي إن كان فارغاً**.
 *
 * ⚠️ كانت شاشاتُ اللوحة تطبع `—` في «القسم» و«الحساب» و«الهاتف»
 *    و«البريد» حتى حين لا شيء فيها: أسطرٌ تُقرأ ولا تقول شيئاً، تدفع
 *    أزرارَ العمل إلى أسفل الشاشة. والفارغُ لا يُعرض أصلاً.
 *
 * ⚠️ **ومكانُه ملفٌّ مشترك لا نسخةٌ في كل شاشة**: كُتب أوّلاً داخل
 *    `OrdersEditor` (٠٧-٠٨)، ونسخةٌ ثانيةٌ منه تفترق عنه بعد شهر —
 *    فيصير عرضُ البيانات في شاشةٍ غيرَه في أختها بلا سبب.
 */
export default function Fact({
  k,
  v,
  tone,
}: {
  /** اسم الحقل — العمود الأيسر، بعرضٍ ثابت فتصطفّ القيم */
  k: string;
  v: React.ReactNode;
  /** أصنافٌ إضافية على القيمة — لونُ خطرٍ أو خطٌّ ثابت العرض */
  tone?: string;
}) {
  if (v === null || v === undefined || v === "" || v === "—") return null;
  return (
    <div className="flex gap-3 text-sm">
      <span className="w-24 shrink-0 text-muted">{k}</span>
      <span className={`min-w-0 flex-1 font-medium ${tone ?? ""}`}>{v}</span>
    </div>
  );
}
