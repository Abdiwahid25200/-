/**
 * 🐌 **قراءةٌ واحدة لكل وثيقة — لا واحدةٌ لكل قطعة** (بلاغ التقطيع ٠٤-٠٨).
 *
 * المشكلة التي يحلّها، وقد قِيست في الكود:
 *
 * | الصفحة | ماذا كان يحدث في جوّال الزبون |
 * |---|---|
 * | أيّ صفحة | القائمة الجانبية تقرأ **إعدادات برواقو** ورصيدَه |
 * | الرئيسية | وبطاقة برواقو تقرأ **الوثيقتين نفسيهما** مرّةً ثانية |
 * | أيّ صفحة | شريط الحالة يقرأ **عدّاد الثقة**، وشريط الأرقام يقرؤه ثانيةً |
 * | الشراء والسلّة | خصمُ النقاط يقرأ الإعدادات والرصيد مرّةً ثالثة |
 *
 * أربعُ رحلاتٍ إلى الشبكة لوثيقتين — وكلُّ رحلةٍ تعود فتُعيد رسم قطعتها
 * وحدها، **فترى الصفحة تقفز مرّةً بعد مرّة**. وذلك هو «التقطيع» الذي
 * وصفته.
 *
 * وهذه الدالة تجعل النداءات المتزامنة **تتقاسم رحلةً واحدة**، وتحفظ
 * الجواب لحظاتٍ لمن يسأل بعدها.
 *
 * ⚠️ **وفي المتصفّح وحده**: على الخادم كل طلب زبونٍ مستقلّ، وحفظُ جوابٍ
 *    بينها يعني أن يرى زبونٌ رصيدَ غيره. فلا ذاكرة هنا إلا في الجهاز.
 * ⚠️ **ومهلةُ صفر تعني: شاركوا الرحلة ولا تحفظوا الجواب** — وهي ما
 *    يليق بالرصيد: لا يُقرأ قديماً بعد شراءٍ أنقصه.
 */

type Entry = { at: number; p: Promise<unknown> };

const live = new Map<string, Entry>();

export function share<T>(key: string, ttlMs: number, run: () => Promise<T>): Promise<T> {
  if (typeof window === "undefined") return run();

  const hit = live.get(key);
  if (hit && Date.now() - hit.at <= ttlMs) return hit.p as Promise<T>;

  const p = run();
  live.set(key, { at: Date.now(), p });

  /* ⚠️ **والفشل لا يُحفظ**: خطأُ شبكةٍ عابر يجب ألّا يُعاد على كل من
     يسأل خلال الدقيقة التالية — يُنسى فوراً ليُعاد السؤال. */
  void p.catch(() => live.delete(key));

  /* ومهلةُ صفر: تُمحى ما إن تنتهي، فتُشارَك الرحلةُ الجارية وحدها */
  if (ttlMs <= 0) void p.finally(() => live.delete(key));

  return p;
}

/** يُنادى بعد كل كتابةٍ تُبطل المحفوظ — كالحفظ من اللوحة */
export const forget = (key?: string) => (key ? live.delete(key) : live.clear());

/**
 * ⏳ **ما لا يُقرأ في أوّل نظرةٍ لا يُحمَّل في أوّل لحظة.**
 *
 * عدّادُ الثقة وشريط الأرقام ورصيدُ برواقو أخبارٌ **تحت الطيّة أو في
 * طرف السطر** — وقراءتُها وقتَ فتح الصفحة تزاحم رسمَها. فتُؤجَّل إلى
 * أوّل فراغٍ للجهاز، وبحدٍّ أقصى ثانيةٌ ونصف فلا تتأخّر عن الحاجة.
 *
 * ⚠️ **ويُعاد ما يُلغي**: كل نداءٍ يعيد دالّةَ إلغائه، فلا يُنفَّذ شيءٌ
 *    بعد أن تُغلق الصفحة أو يخرج المكوّن.
 */
export function onIdle(run: () => void): () => void {
  if (typeof window === "undefined") return () => {};
  const w = window as unknown as {
    requestIdleCallback?: (cb: () => void, o?: { timeout: number }) => number;
    cancelIdleCallback?: (id: number) => void;
  };
  let done = false;
  const go = () => {
    if (done) return;
    done = true;
    run();
  };
  const t = setTimeout(go, 1500);
  const id = w.requestIdleCallback?.(go, { timeout: 1500 });
  return () => {
    done = true;
    clearTimeout(t);
    if (id !== undefined) w.cancelIdleCallback?.(id);
  };
}
