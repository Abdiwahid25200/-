/**
 * 🎬 **رمزُ فيديو يوتيوب من أيّ شكلٍ يُلصق** — طلبها (٠٧-٠٨): «بدي في
 * صفحة help أن أستطيع إضافة **رابط** فيديو».
 *
 * ⚠️ **والحقل كان يطلب الرمز لا الرابط**: أحدَ عشرَ محرفاً تُستخرج من
 *    وسط رابطٍ طويل بيدها. وزرُّ المشاركة في يوتيوب يعطي **رابطاً**،
 *    فكان عليها أن تعرف أيّ جزءٍ منه هو «الرمز» — وأن تقتطعه بلا خطأ
 *    من شاشة جوّال. فيُقبل الرابطُ كما هو الآن، ويُقبل الرمزُ أيضاً
 *    لمن كتبه قبل اليوم.
 *
 * والأشكال المقبولة كلّها:
 *   youtube.com/watch?v=ID · youtu.be/ID · youtube.com/shorts/ID
 *   youtube.com/embed/ID · youtube.com/live/ID · m.youtube.com/…
 *   ومعها أيّ زوائد (`&t=30s` · `?si=…` · `#`) — تُتجاهَل.
 */
export function youtubeId(raw: string): string {
  const s = String(raw ?? "").trim();
  if (!s) return "";

  /* الرمز وحده: أحدَ عشرَ محرفاً من مجموعة يوتيوب */
  if (/^[\w-]{11}$/.test(s)) return s;

  const m = s.match(
    /(?:youtube\.com\/(?:watch\?(?:[^#]*&)?v=|embed\/|shorts\/|live\/|v\/)|youtu\.be\/)([\w-]{11})/i,
  );
  return m ? m[1] : "";
}

